(function attachQuickAddService(globalScope) {
    'use strict';
    class QuickAddService {
        constructor(options = {}) {
            this.parseYoutubeId = options.parseYoutubeId || (() => null);
            this.parsePlaylistId = options.parsePlaylistId || (() => null);
            this.resolveSoundcloudUrl = options.resolveSoundcloudUrl || (async value => value);
            this.fetchMetadata = options.fetchMetadata || (async () => ({}));
            this.parseDuration = options.parseDuration || (() => 0);
            this.now = options.now || Date.now;
            this.random = options.random || Math.random;
        }
        classify(input) {
            const value = String(input || '').trim();
            if (!value) return { kind: 'invalid' };
            const playlistId = this.parsePlaylistId(value);
            const videoId = this.parseYoutubeId(value);
            // YouTube tự gắn list=RD... cho Mix/radio khi người dùng chỉ chia sẻ
            // một video. Trường hợp này phải giữ là bài đơn.
            const isAutoGeneratedMix = Boolean(videoId && /^RD/i.test(String(playlistId || '')));
            if (playlistId && !isAutoGeneratedMix) return { kind: 'playlist', url: value, playlistId };
            if (value.includes('spotify.com') || value.startsWith('spotify:')) return { kind: 'unsupported', provider: 'spotify' };
            if (value.includes('soundcloud.com')) return { kind: 'track', type: 'soundcloud', url: value };
            return videoId
                ? { kind: 'track', type: 'youtube', videoId, url: `https://www.youtube.com/watch?v=${videoId}` }
                : { kind: 'invalid' };
        }
        async resolve(input) {
            const media = this.classify(input);
            if (media.kind !== 'track') return media;
            if (media.type === 'soundcloud') {
                media.url = await this.resolveSoundcloudUrl(media.url);
                media.soundcloudUrl = media.url;
            }
            media.metadata = await this.fetchMetadata(media.type, media.videoId || null, media.soundcloudUrl || null);
            return media;
        }
        createSong(media, options = {}) {
            const source = media.metadata ? media : {
                type: media.type || (media.soundcloudUrl ? 'soundcloud' : 'youtube'),
                videoId: media.videoId || (media.type !== 'soundcloud' ? (this.parseYoutubeId(media.id) || this.parseYoutubeId(media.songLink)) : null),
                soundcloudUrl: media.soundcloudUrl || null,
                metadata: media
            };
            const timestamp = this.now();
            const owner = Boolean(options.isOwnerAdd);
            return {
                id: `${timestamp}${this.random().toString(36).slice(2, 7)}`,
                type: source.type, videoId: source.videoId || null, spotifyId: source.spotifyId || null,
                soundcloudUrl: source.soundcloudUrl || null, title: source.metadata.title,
                thumbnail: source.metadata.thumbnail, author: source.metadata.author || '',
                duration: this.parseDuration(source.metadata.duration) || '', donorName: options.donorName || 'Em Dứa',
                amount: Number(options.amount ?? 100000000), message: '', start: 0, end: null,
                timestamp, localAddedAt: timestamp, views: source.metadata.views || '',
                isOwnerAdd: owner, isQuickAdd: !owner
            };
        }
    }
    globalScope.QuickAddService = QuickAddService;
    if (typeof module !== 'undefined' && module.exports) module.exports = QuickAddService;
})(typeof window !== 'undefined' ? window : globalThis);
